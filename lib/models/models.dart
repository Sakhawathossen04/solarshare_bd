/// Interval energy reading (hourly) for a user.
/// Mirrors the doc's meter data gateway record (generation, consumption,
/// export, import, meter status).
class MeterReading {
  final String userId;
  final DateTime timestamp;
  final double solarGeneration; // kWh generated by solar
  final double consumption; // locally consumed
  final double gridExport; // exported to grid
  final double gridImport; // imported from grid
  final bool meterOnline;

  const MeterReading({
    required this.userId,
    required this.timestamp,
    required this.solarGeneration,
    required this.consumption,
    required this.gridExport,
    required this.gridImport,
    this.meterOnline = true,
  });

  double get selfUse =>
      solarGeneration - gridExport < 0 ? 0 : solarGeneration - gridExport;
}

