/// Producer surplus offer in the marketplace.
class EnergyOffer {
  final String id;
  final String producerId;
  final String producerName;
  final String area;
  final double kwh;
  final double ratePerKwh; // ৳
  final DateTime windowStart;
  final OfferStatus status;

  const EnergyOffer({
    required this.id,
    required this.producerId,
    required this.producerName,
    required this.area,
    required this.kwh,
    required this.ratePerKwh,
    required this.windowStart,
    required this.status,
  });
}

enum OfferStatus { pending, settled }

/// A settled trade between a producer and consumer.
class Trade {
  final String id;
  final String offerId;
  final String producerId;
  final String consumerId;
  final double kwh;
  final double ratePerKwh;
  final DateTime settledAt;

  const Trade({
    required this.id,
    required this.offerId,
    required this.producerId,
    required this.consumerId,
    required this.kwh,
    required this.ratePerKwh,
    required this.settledAt,
  });

  double get total => kwh * ratePerKwh;
}

/// Wallet transaction line.
enum TxnType { credit, debit }

class WalletTxn {
  final String id;
  final String title;
  final double amount; // positive number
  final TxnType type;
  final DateTime date;

  const WalletTxn({
    required this.id,
    required this.title,
    required this.amount,
    required this.type,
    required this.date,
  });

  double get signed => type == TxnType.credit ? amount : -amount;
}

